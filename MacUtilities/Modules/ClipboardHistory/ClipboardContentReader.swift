import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

enum ClipboardSkipReason: String, Equatable {
    case concealed
    case transient
    case tooLarge
    case imagesDisabled
    case unsupported
}

enum ClipboardReadResult: Equatable {
    case content(CapturedClipboardContent)
    case empty
    case skipped(ClipboardSkipReason)
}

struct ClipboardReaderOptions {
    var ignoreConcealed = true
    var ignoreTransient = true
    var saveImages = true
    var maxBytes = 25 * 1024 * 1024

    init() {}

    init(settings: ClipboardSettings) {
        ignoreConcealed = settings.ignoreConcealedContent
        ignoreTransient = settings.ignoreTransientContent
        saveImages = settings.saveImages
        maxBytes = settings.maxItemBytes
    }
}

/// Читает текущее содержимое NSPasteboard, не изменяя его.
///
/// Сохраняются ВСЕ представления каждого объекта (RTF, HTML, PNG, TIFF, file URL и т.д.),
/// чтобы при восстановлении приложение-получатель могло выбрать лучший формат.
enum ClipboardContentReader {
    // Маркеры по соглашению http://nspasteboard.org — их выставляют менеджеры паролей и
    // утилиты, генерирующие временное содержимое. Это единственный надёжный способ
    // распознать «секретные» данные; эвристик для паролей/кодов здесь намеренно нет.
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]
    static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Типы-«обещания» (file promises): их данные нельзя корректно воспроизвести позже.
    static func isSkippedType(_ type: String) -> Bool {
        type.hasPrefix("com.apple.pasteboard.promised")
            || type == "com.apple.NSFilePromiseItemMetaData"
            || type == "NSPromiseContentsPboardType"
    }

    static let plainTextTypes = ["public.utf8-plain-text", "public.utf16-external-plain-text", "public.utf16-plain-text", "public.plain-text", "NSStringPboardType"]
    static let fileURLType = "public.file-url"
    static let urlType = "public.url"
    static let rtfTypes = ["public.rtf", "com.apple.flat-rtfd", "com.apple.rtfd"]
    static let htmlType = "public.html"
    /// Порядок предпочтения форматов изображений (лучший первым).
    static let preferredImageTypes = ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif", "org.webmproject.webp"]

    // MARK: - Чтение

    static func read(_ pasteboard: NSPasteboard, options: ClipboardReaderOptions) -> ClipboardReadResult {
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return .empty }

        let allTypes = Set(pasteboardItems.flatMap { $0.types.map(\.rawValue) })
        if allTypes.isEmpty { return .empty }
        if options.ignoreConcealed && !allTypes.isDisjoint(with: concealedTypes) { return .skipped(.concealed) }
        if options.ignoreTransient && !allTypes.isDisjoint(with: transientTypes) { return .skipped(.transient) }

        var total = 0
        var items: [CapturedPasteboardItem] = []
        for pasteboardItem in pasteboardItems {
            var representations: [ClipboardRepresentation] = []
            for type in pasteboardItem.types where !isSkippedType(type.rawValue) {
                guard let data = pasteboardItem.data(forType: type) else { continue }
                total += data.count
                if total > options.maxBytes { return .skipped(.tooLarge) }
                representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
            }
            if !representations.isEmpty {
                items.append(CapturedPasteboardItem(representations: representations))
            }
        }
        guard !items.isEmpty else { return .skipped(.unsupported) }
        return process(items: items, options: options)
    }

    /// Чистая функция: классификация + фильтрация по настройкам. Покрыта тестами.
    static func process(items: [CapturedPasteboardItem], options: ClipboardReaderOptions) -> ClipboardReadResult {
        guard var content = analyze(items: items) else { return .skipped(.unsupported) }
        if !options.saveImages {
            if content.kind == .image { return .skipped(.imagesDisabled) }
            // Для текста/файлов убираем сопутствующие картинки (например, превью из Office).
            content.items = content.items.map { item in
                CapturedPasteboardItem(representations: item.representations.filter { !isImageType($0.type) })
            }.filter { !$0.representations.isEmpty }
            if content.items.isEmpty { return .skipped(.imagesDisabled) }
        }
        return .content(content)
    }

    // MARK: - Классификация

    static func isImageType(_ type: String) -> Bool {
        if preferredImageTypes.contains(type) { return true }
        guard let utType = UTType(type) else { return false }
        return utType.conforms(to: .image)
    }

    static func analyze(items: [CapturedPasteboardItem]) -> CapturedClipboardContent? {
        guard !items.isEmpty else { return nil }

        let fileURLs = items.compactMap { item -> URL? in
            guard let data = item.data(for: fileURLType) else { return nil }
            return URL(dataRepresentation: data, relativeTo: nil)
        }.filter(\.isFileURL)

        let texts = items.compactMap { plainText(of: $0) }
        let text = texts.joined(separator: "\n")
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let first = items[0]
        let linkString = first.data(for: urlType).flatMap { String(data: $0, encoding: .utf8) }
            ?? (isSingleWebURL(trimmed) ? trimmed : nil)
        let image = bestImage(in: first)
        let rtfData = rtfTypes.lazy.compactMap { first.data(for: $0) }.first
        let htmlData = first.data(for: htmlType)

        var kind: ClipboardKind
        var preview: String
        var canonical = Data()

        if !fileURLs.isEmpty {
            kind = .files
            preview = fileURLs.map(\.path).joined(separator: "\n")
            canonical = Data(preview.utf8)
        } else if let image, trimmed.isEmpty || isSingleWebURL(trimmed) {
            // Скриншоты и «Копировать изображение» из браузеров: картинка, возможно с URL.
            kind = .image
            preview = imageDescription(type: image.type, data: image.data)
            canonical = image.data
        } else if let linkString, !linkString.isEmpty, trimmed.isEmpty || trimmed == linkString || isSingleWebURL(trimmed) {
            kind = .link
            preview = linkString
            canonical = Data(linkString.utf8)
        } else if rtfData != nil || htmlData != nil {
            kind = .richText
            preview = trimmed.isEmpty ? (textFromRichData(rtf: rtfData, html: htmlData) ?? "") : text
            canonical = Data(preview.utf8) + (htmlData ?? rtfData ?? Data())
        } else if !trimmed.isEmpty {
            kind = .text
            preview = text
            canonical = Data(text.utf8)
        } else if let image {
            kind = .image
            preview = imageDescription(type: image.type, data: image.data)
            canonical = image.data
        } else if !text.isEmpty {
            // Только пробелы / переводы строк — это тоже валидный текст.
            kind = .text
            preview = text
            canonical = Data(text.utf8)
        } else if items.allSatisfy({ $0.types.allSatisfy(plainTextTypes.contains) }) {
            // Пустая строка (например, «копирование» без выделения) — сохранять нечего.
            return nil
        } else {
            kind = .other
            preview = first.types.joined(separator: ", ")
            for item in items { for rep in item.representations { canonical.append(Data(rep.type.utf8)); canonical.append(rep.data) } }
        }

        let size = image.flatMap { imagePixelSize($0.data) }
        var hasher = SHA256()
        hasher.update(data: Data(kind.rawValue.utf8))
        hasher.update(data: canonical)
        let hash = hasher.finalize().map { String(format: "%02x", $0) }.joined()

        return CapturedClipboardContent(items: items,
                                        kind: kind,
                                        previewText: String(preview.prefix(5000)),
                                        imagePixelSize: kind == .image ? size : nil,
                                        contentHash: hash)
    }

    static func plainText(of item: CapturedPasteboardItem) -> String? {
        if let data = item.data(for: "public.utf8-plain-text") ?? item.data(for: "NSStringPboardType") ?? item.data(for: "public.plain-text") {
            return String(data: data, encoding: .utf8)
        }
        if let data = item.data(for: "public.utf16-external-plain-text") ?? item.data(for: "public.utf16-plain-text") {
            return String(data: data, encoding: .utf16)
        }
        return nil
    }

    static func bestImage(in item: CapturedPasteboardItem) -> ClipboardRepresentation? {
        for type in preferredImageTypes {
            if let data = item.data(for: type) { return ClipboardRepresentation(type: type, data: data) }
        }
        return item.representations.first { isImageType($0.type) }
    }

    static func isSingleWebURL(_ string: String) -> Bool {
        guard !string.isEmpty, !string.contains(where: \.isWhitespace),
              let url = URL(string: string), let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https", "ftp", "mailto"].contains(scheme) && (url.host != nil || scheme == "mailto")
    }

    static func imagePixelSize(_ data: Data) -> CGSize? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = props[kCGImagePropertyPixelWidth] as? Int,
              let height = props[kCGImagePropertyPixelHeight] as? Int else { return nil }
        return CGSize(width: width, height: height)
    }

    private static func imageDescription(type: String, data: Data) -> String {
        let format = UTType(type)?.preferredFilenameExtension?.uppercased() ?? "Image"
        if let size = imagePixelSize(data) {
            return "\(format) \(Int(size.width))×\(Int(size.height))"
        }
        return format
    }

    /// Текст из RTF (быстро, без WebKit). HTML разбирается упрощённо — только для предпросмотра.
    private static func textFromRichData(rtf: Data?, html: Data?) -> String? {
        if let rtf, let attributed = NSAttributedString(rtf: rtf, documentAttributes: nil) {
            return attributed.string
        }
        if let html, let string = String(data: html, encoding: .utf8) {
            let stripped = string.replacingOccurrences(of: "<[^>]+>", with: " ", options: .regularExpression)
                .replacingOccurrences(of: "&nbsp;", with: " ")
                .replacingOccurrences(of: "&amp;", with: "&")
                .replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            return stripped.trimmingCharacters(in: .whitespacesAndNewlines)
        }
        return nil
    }
}

/// Восстанавливает сохранённые представления в NSPasteboard.
enum ClipboardContentWriter {
    /// Возвращает новый changeCount, чтобы монитор не принял нашу запись за новое копирование.
    @discardableResult
    static func write(_ items: [CapturedPasteboardItem], to pasteboard: NSPasteboard) -> Int {
        let pasteboardItems = items.map { item -> NSPasteboardItem in
            let pasteboardItem = NSPasteboardItem()
            for representation in item.representations {
                pasteboardItem.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
            }
            return pasteboardItem
        }
        pasteboard.clearContents()
        if !pasteboard.writeObjects(pasteboardItems) {
            Log.clipboard.error("NSPasteboard.writeObjects returned false")
        }
        return pasteboard.changeCount
    }
}
